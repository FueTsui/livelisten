using System.Globalization;

namespace LiveListen.Services;

/// <summary>UI strings in Simplified Chinese and English. Short by design.</summary>
internal static class Loc
{
    public static bool English { get; private set; }

    public static string Tag => English ? "en-US" : "zh-Hans";

    public static void Init(string setting)
    {
        var name = setting is "" or "system" ? CultureInfo.CurrentUICulture.Name : setting;
        English = !name.StartsWith("zh", StringComparison.OrdinalIgnoreCase);
    }

    public static string T(string key)
    {
        var table = English ? En : Zh;
        return table.TryGetValue(key, out var text) ? text : Zh.GetValueOrDefault(key, key);
    }

    public static string F(string key, params object[] args) => string.Format(CultureInfo.CurrentCulture, T(key), args);

    /// <summary>Message for an engine error or notice code.</summary>
    public static string Error(string code)
    {
        var key = "error." + code;
        var text = T(key);
        return text == key ? F("error.generic", code) : text;
    }

